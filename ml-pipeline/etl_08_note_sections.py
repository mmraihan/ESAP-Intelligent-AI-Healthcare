"""
etl_08_note_sections.py
=======================
Extracts leakage-safe intake-only sections from discharge summaries into
ml.note_intake_sections.

WHY THIS EXISTS
---------------
Discharge summaries contain the final diagnoses written AFTER the stay ends.
Feeding the full note into a model is catastrophic label leakage.  We can
only use the sections written at / before admission time.

APPROACH
--------
1. Find the DROP BOUNDARY: the earliest marker that signals post-admission
   content (Brief Hospital Course, Discharge Diagnosis, etc.).
   - Fail-closed: if no boundary is found, DROP the entire note.
2. Truncate the note at that boundary.
3. Extract named safe sections from the truncated text by their headers.
4. Store section_name + section_text per (hadm_id, section_name).

SAFE SECTION NAMES (normalized)
--------------------------------
  chief_complaint        - Chief Complaint
  hpi                    - History of Present Illness
  pmh                    - Past Medical History
  meds_on_admission      - Medications on Admission / Home Medications
  allergies              - Allergies
  social_hx              - Social History
  family_hx              - Family History
  physical_exam          - Physical Exam (admission exam only)
  review_of_systems      - Review of Systems

NOTE: "Pertinent Results" is intentionally EXCLUDED even though it appears
before the boundary in ~96% of notes.  It contains in-hospital labs that
are strictly post-t0 data.

OBSERVED HEADER PATTERNS (from real MIMIC-IV notes)
----------------------------------------------------
MIMIC-IV discharge summaries are generated by a templated EHR system and
are fairly uniform, but exhibit these variations:

- Title case standard:  "Chief Complaint:"
- UPPERCASE style:      "CHIEF COMPLAINT:" (less common, ~5% of notes)
- Embedded sub-labels:  "Physical Exam:\nADMISSION PHYSICAL EXAM:"
- Inline content:       "History of Present Illness:\nText starts here..."
- Blank-line separated: headers followed by empty line then content
- Delimiter bars:       "=======" or "-------" sometimes separate subsections
- Medications variants: "Medications on Admission:", "HOME MEDICATIONS:",
                        "Preadmission Medications:"
- Physical Exam admits: "Physical Exam:", "ADMISSION PHYSICAL EXAM:",
                        "Physical Exam on Admission:", "PHYSICAL EXAMINATION:"
- PMH aliases:          "Past Medical History:", "PAST MEDICAL HISTORY:",
                        "PAST MEDICAL/SURGICAL HISTORY:"

BOUNDARY MARKERS seen in the wild
----------------------------------
- "Brief Hospital Course:"   (present in 88% of notes)
- "Pertinent Results:"       (present in 96%; always BEFORE BHC -- keep as
                              hard boundary so we don't accidentally include labs)
- "Discharge Diagnosis:"     (96%)
- "Discharge Diagnoses:"
- "Final Diagnosis:"
- "Discharge Medications:"   (98%)
- "Discharge Condition:"
- "Discharge Instructions:"
- "Discharge Disposition:"
- "Followup Instructions:"
- "Hospital Course:"         (alternate phrasing, ~1.5%)
- "Active Issues:" / "ACTIVE ISSUES:" / "Acute Issues:" / "ACUTE ISSUES:"
  -- used in problem-list-style notes that omit "Brief Hospital Course"
- "Chronic Issues:" / "CHRONIC ISSUES:"
- "Discharge Physical Exam:" / "DISCHARGE PHYSICAL EXAM:" / "DISCHARGE PE:"
  -- DISCHARGE exam is post-stay; ADMISSION exam is safe
- "Discharge Labs:" / "DISCHARGE LABS:"
- "Discharge:" (standalone header sometimes used)
- "Transitional Issues:" / "TRANSITIONAL ISSUES:"

EDGE CASES HANDLED
------------------
- "Assessment and Plan" can appear embedded INSIDE "Brief Hospital Course:"
  text, not as its own standalone boundary. We only trigger it as a boundary
  if it appears as a standalone line header.
- Notes with NO recognizable boundary (~28 notes, <0.01%) are dropped.
- Physical Exam: when both "Physical Exam:" and "ADMISSION PHYSICAL EXAM:"
  appear on adjacent lines, we capture from the first occurrence.
- "Discharge Physical Exam" is a boundary marker (post-discharge); admission
  physical exam is safe.
- ~5% of notes use "Medications on Admission:" placed AFTER the boundary
  (e.g. templated "Discharge Medications" block includes a reconciled prior
  list).  The boundary truncation handles this correctly.
"""

import re
import sys
import time
from typing import Dict, List, Optional
from db import connect

# ---------------------------------------------------------------------------
# REGEX PATTERN DICTIONARIES -- audit/adjust here, not buried in code
# ---------------------------------------------------------------------------

# ---- DROP BOUNDARIES (earliest match wins; note truncated at this point) ----
# Each value is a raw regex string.  Patterns are matched with re.IGNORECASE
# against every line in the note.  A line "matches" if the pattern is found
# at the START of the stripped line content.

BOUNDARY_PATTERNS = {
    # Primary boundary -- present in ~88% of notes
    "brief_hospital_course": r"brief\s+hospital\s+course\s*[:\-]?",

    # Problem-list style notes (no BHC header)
    "active_issues":         r"(?:acute|active)\s+issues?\s*[:\-=]+",
    "chronic_issues":        r"chronic\s+issues?\s*[:\-=]+",

    # In-hospital data (labs/results) -- always before BHC, still post-t0
    "pertinent_results":     r"pertinent\s+results?\s*[:\-]?",

    # Discharge-tagged sections -- clearly post-stay
    "discharge_diagnosis":   r"discharge\s+diagnos(?:is|es|tic)\s*[:\-]?",
    "final_diagnosis":       r"final\s+diagnos(?:is|es)\s*[:\-]?",
    "primary_diagnosis":     r"primary\s+diagnos(?:is|es)\s*[:\-]?",
    "discharge_medications": r"discharge\s+med(?:ication)?s?\s*[:\-]?",
    "discharge_condition":   r"discharge\s+condition\s*[:\-]?",
    "discharge_instructions":r"discharge\s+instructions?\s*[:\-]?",
    "discharge_disposition": r"discharge\s+disposition\s*[:\-]?",
    "followup_instructions": r"follow[\-\s]?up\s+instructions?\s*[:\-]?",

    # Exam/labs tagged as discharge
    "discharge_physical_exam": r"discharge\s+(?:physical\s+)?exam(?:ination)?\s*[:\-]?",
    "physical_exam_discharge": r"physical\s+exam(?:ination)?\s+(?:on\s+)?discharge\s*[:\-]?",
    "discharge_labs":        r"discharge\s+labs?\s*[:\-]?",

    # Standalone "Discharge:" header (rarely used)
    "discharge_standalone":  r"discharge\s*:\s*$",

    # Assessment embedded as its own section heading (not inside BHC body)
    "assessment_and_plan":   r"assessment\s+and\s+plan\s*[:\-]?",

    # Transitional issues = care transition planning = post-stay
    "transitional_issues":   r"transitional\s+issues?\s*[:\-=]+",

    # Hospital course variants
    "hospital_course":       r"(?:in[\-\s]?)?hospital\s+course\s*[:\-]?",
}

# Compile boundaries into a single pattern for fast scanning.
# We match at the START of a stripped line (after optional leading spaces/symbols).
_BOUNDARY_LINE_RE = re.compile(
    r"^\s*(?:[#\*\-=_]+\s*)?(" +
    "|".join(f"(?P<b{i}>{p})" for i, p in enumerate(BOUNDARY_PATTERNS.values())) +
    r")",
    re.IGNORECASE,
)

# ---- SAFE (INTAKE) SECTION HEADERS ----------------------------------------
# List of (normalized_name, regex_pattern) tuples.
# Patterns match a standalone header line (stripped).
# Order matters: more specific patterns before more general ones.
# We use these to slice out section text AFTER the boundary truncation.

INTAKE_SECTION_PATTERNS = [
    # Chief Complaint
    ("chief_complaint",
     r"chief\s+complaint\s*[:\-]?"),

    # History of Present Illness
    ("hpi",
     r"(?:history\s+of\s+present\s+illness|h(?:\.?o\.?)?p\.?i\.?)\s*[:\-]?"),

    # Past Medical History (incl. "Past Medical/Surgical History")
    ("pmh",
     r"past\s+(?:medical|surgical|med(?:ical)?[/&]\s*surgical)\s+history\s*[:\-]?"),

    # Medications on Admission (all common variants)
    ("meds_on_admission",
     r"(?:medications?\s+on\s+admission"
     r"|home\s+medications?"
     r"|admission\s+medications?"
     r"|pre[\-\s]?admission\s+medications?"
     r"|current\s+medications?\s+(?:list\s+)?"
     r")\s*[:\-]?"),

    # Allergies
    ("allergies",
     r"allergies\s*(?:and\s+adverse\s+(?:drug\s+)?reactions?)?\s*[:\-]?"),

    # Social History
    ("social_hx",
     r"social\s+history\s*[:\-]?"),

    # Family History
    ("family_hx",
     r"family\s+history\s*[:\-]?"),

    # Physical Exam -- ADMISSION ONLY
    # Matches "Physical Exam:", "ADMISSION PHYSICAL EXAM:", etc.
    # Must NOT match "Discharge Physical Exam" (already caught by boundary).
    ("physical_exam",
     r"(?:admission\s+)?physical\s+exam(?:ination)?\s*(?:on\s+admission)?\s*[:\-]?"),

    # Review of Systems
    ("review_of_systems",
     r"review\s+of\s+systems?\s*[:\-]?"),
]

# Compile each intake section pattern for line matching
_INTAKE_COMPILED = [
    (name, re.compile(r"^\s*" + pat, re.IGNORECASE))
    for name, pat in INTAKE_SECTION_PATTERNS
]

# All intake header patterns combined (for splitting the note into chunks)
_ALL_INTAKE_RE = re.compile(
    r"^\s*(?:" + "|".join(p for _, p in INTAKE_SECTION_PATTERNS) + r")\s*$",
    re.IGNORECASE | re.MULTILINE,
)

# ---------------------------------------------------------------------------
# CORE PARSING FUNCTIONS
# ---------------------------------------------------------------------------

def find_boundary_position(text: str) -> Optional[int]:
    """
    Return the character position of the first drop boundary in `text`,
    or None if no boundary is found (caller should drop the note).

    Scans line by line and returns the start offset of the first matching
    boundary line.
    """
    pos = 0
    for line in text.splitlines(keepends=True):
        stripped = line.strip()
        if stripped and _BOUNDARY_LINE_RE.match(stripped):
            return pos
        pos += len(line)
    return None  # no boundary found


def parse_note(text: str) -> Optional[Dict[str, str]]:
    """
    Parse a single discharge note.

    Returns a dict mapping normalized_section_name -> section_text,
    or None if the note should be dropped (no boundary found, or
    only empty sections).

    Strategy:
    1. Find drop boundary position; drop note if absent.
    2. Truncate text at boundary.
    3. Walk through the truncated text line-by-line.
    4. When a line matches an intake section header, record that we're
       in that section and accumulate subsequent lines until the next
       recognized header (intake OR any other major header line).
    """
    # Step 1+2: find and apply boundary
    boundary_pos = find_boundary_position(text)
    if boundary_pos is None:
        return None

    safe_text = text[:boundary_pos]

    # Step 3+4: scan the safe text line by line
    sections: Dict[str, List[str]] = {}
    current_section: Optional[str] = None
    current_lines: List[str] = []

    # A "major header line" is a short line that looks like a section header
    # (ends with : and is under ~70 chars, or is ALL-CAPS under ~60 chars).
    # We use this to detect section transitions for sections we don't capture.
    def is_any_header(line: str) -> Optional[str]:
        """Return matched section name if line is an intake header, else None."""
        stripped = line.strip()
        for name, compiled in _INTAKE_COMPILED:
            # Match the ENTIRE stripped line against the header pattern
            if compiled.match(stripped) and len(stripped) < 80:
                # Sanity: must be a header-style line (ends in : or is short)
                if stripped.endswith(":") or len(stripped) < 50:
                    return name
        return None

    def looks_like_any_section_header(line: str) -> bool:
        """True if the line looks like ANY section header (to end a section)."""
        s = line.strip()
        if not s:
            return False
        # Short line that ends with colon
        if s.endswith(":") and len(s) < 70:
            return True
        # ALL-CAPS short line without colon (e.g. "REVIEW OF SYSTEMS")
        if s == s.upper() and len(s) < 60 and re.match(r"^[A-Z][A-Z\s/\(\)\-,\.]+$", s):
            return True
        return False

    for line in safe_text.splitlines(keepends=False):
        matched_section = is_any_header(line)
        if matched_section is not None:
            # Save the previous section's accumulated lines
            if current_section is not None:
                sections.setdefault(current_section, []).extend(current_lines)
            current_section = matched_section
            current_lines = []
        elif current_section is not None:
            # We're inside an intake section
            if looks_like_any_section_header(line):
                # Another (non-intake) section is starting -- end this section
                # but do NOT switch to it
                sections.setdefault(current_section, []).extend(current_lines)
                current_section = None
                current_lines = []
            else:
                current_lines.append(line)

    # Flush final section
    if current_section is not None:
        sections.setdefault(current_section, []).extend(current_lines)

    # Clean up each section: strip leading/trailing blank lines, join
    result: Dict[str, str] = {}
    for name, lines in sections.items():
        text_block = "\n".join(lines).strip()
        if text_block:  # skip empty sections
            result[name] = text_block

    return result if result else None


# ---------------------------------------------------------------------------
# DDL
# ---------------------------------------------------------------------------

CREATE_TABLE_SQL = """
CREATE TABLE IF NOT EXISTS ml.note_intake_sections (
    hadm_id       INTEGER  NOT NULL,
    section_name  TEXT     NOT NULL,
    section_text  TEXT     NOT NULL
);
"""

CREATE_INDEX_SQL = """
CREATE INDEX IF NOT EXISTS note_intake_sections_hadm_idx
    ON ml.note_intake_sections (hadm_id);
"""

TRUNCATE_SQL = "TRUNCATE ml.note_intake_sections;"


# ---------------------------------------------------------------------------
# MAIN ETL
# ---------------------------------------------------------------------------

BATCH_SIZE = 10_000


def run():
    print("=" * 70)
    print("etl_08_note_sections.py  --  extract intake sections from notes")
    print("=" * 70)

    conn = connect()
    conn.autocommit = False
    cur = conn.cursor()

    # --- Create / reset table ---
    print("\n[1/4] Creating ml.note_intake_sections ...")
    cur.execute(CREATE_TABLE_SQL)
    cur.execute(TRUNCATE_SQL)
    conn.commit()
    print("      Table ready (truncated).")

    # --- Load cohort hadm_ids for filtering ---
    print("\n[2/4] Loading cohort hadm_ids from ml.cohort_spine ...")
    cur.execute("SELECT hadm_id FROM ml.cohort_spine")
    cohort_hadm_ids = {row[0] for row in cur.fetchall()}
    print(f"      {len(cohort_hadm_ids):,} admissions in cohort.")

    # --- Count total notes ---
    cur.execute("""
        SELECT count(*)
        FROM mimic_note.discharge d
        WHERE d.hadm_id::int IN (SELECT hadm_id FROM ml.cohort_spine)
    """)
    total_notes = cur.fetchone()[0]
    print(f"\n[3/4] Processing {total_notes:,} discharge notes in batches of {BATCH_SIZE:,} ...")

    # Counters
    n_processed   = 0
    n_dropped_no_boundary = 0
    n_dropped_not_in_cohort = 0
    n_notes_with_sections  = 0
    section_counts: Dict[str, int] = {name: 0 for name, _ in INTAKE_SECTION_PATTERNS}

    # Fetch notes in offset batches (server-side cursor for memory efficiency)
    cur.execute("""
        SELECT d.hadm_id::int AS hadm_id, d.text
        FROM mimic_note.discharge d
        WHERE d.hadm_id IS NOT NULL
          AND d.hadm_id::int IN (SELECT hadm_id FROM ml.cohort_spine)
        ORDER BY d.hadm_id
    """)

    insert_cur = conn.cursor()
    batch_rows: List[tuple] = []

    t0 = time.time()
    while True:
        rows = cur.fetchmany(BATCH_SIZE)
        if not rows:
            break

        for hadm_id, text in rows:
            n_processed += 1

            if not text or not text.strip():
                n_dropped_no_boundary += 1
                continue

            sections = parse_note(text)

            if sections is None:
                n_dropped_no_boundary += 1
                continue

            n_notes_with_sections += 1
            for sec_name, sec_text in sections.items():
                batch_rows.append((hadm_id, sec_name, sec_text))
                if sec_name in section_counts:
                    section_counts[sec_name] += 1

        if batch_rows:
            # Use executemany for insertion
            insert_cur.executemany(
                "INSERT INTO ml.note_intake_sections (hadm_id, section_name, section_text) "
                "VALUES (%s, %s, %s)",
                batch_rows,
            )
            conn.commit()
            batch_rows = []

        elapsed = time.time() - t0
        rate = n_processed / elapsed if elapsed > 0 else 0
        pct = 100 * n_processed / total_notes if total_notes > 0 else 0
        print(
            f"      {n_processed:>7,} / {total_notes:,}  ({pct:.1f}%)"
            f"  dropped={n_dropped_no_boundary:,}"
            f"  {rate:.0f} notes/s",
            end="\r",
        )

    # Flush any remaining
    if batch_rows:
        insert_cur.executemany(
            "INSERT INTO ml.note_intake_sections (hadm_id, section_name, section_text) "
            "VALUES (%s, %s, %s)",
            batch_rows,
        )
        conn.commit()

    print()  # newline after \r progress

    # --- Create index ---
    print("\n[4/4] Creating index on hadm_id ...")
    cur.execute(CREATE_INDEX_SQL)
    conn.commit()
    print("      Index created.")

    # --- Stats ---
    print("\n" + "=" * 70)
    print("RESULTS")
    print("=" * 70)
    print(f"  Total notes processed:            {n_processed:>10,}")
    print(f"  Notes dropped (no boundary):      {n_dropped_no_boundary:>10,}  "
          f"({100*n_dropped_no_boundary/n_processed:.2f}%)")
    print(f"  Notes with >= 1 section:          {n_notes_with_sections:>10,}")
    cov = 100 * n_notes_with_sections / n_processed if n_processed else 0
    print(f"  Coverage (notes w/ sections):          {cov:.1f}%")
    print()
    print("  Sections extracted by type:")
    print(f"  {'Section':<28} {'Count':>10}  {'Coverage':>10}")
    print("  " + "-" * 52)
    for name, cnt in sorted(section_counts.items(), key=lambda x: -x[1]):
        pct = 100 * cnt / n_notes_with_sections if n_notes_with_sections else 0
        print(f"  {name:<28} {cnt:>10,}  {pct:>9.1f}%")

    # Verify row count in DB
    cur.execute("SELECT count(*), count(DISTINCT hadm_id) FROM ml.note_intake_sections")
    db_rows, db_hadms = cur.fetchone()
    print(f"\n  DB rows inserted:  {db_rows:,}")
    print(f"  Distinct hadm_ids: {db_hadms:,}")

    conn.close()
    print("\nDone.")


if __name__ == "__main__":
    run()
